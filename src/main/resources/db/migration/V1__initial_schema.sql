-- =====================================================================
-- V1__initial_schema.sql - Initial Schema DDL for EscolaWeb
-- =====================================================================

-- 1. School Settings
CREATE TABLE school_settings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_name character varying(150),
    address character varying(255),
    cep character varying(20),
    phone character varying(20),
    email character varying(150),
    minimum_attendance numeric(5,2),
    minimum_average numeric(3,1),
    period_type character varying(20),
    created_at timestamp(6) without time zone,
    CONSTRAINT school_settings_period_type_check CHECK (period_type IN ('BIMESTER', 'TRIMESTER', 'QUADRIMESTER', 'SEMESTER', 'ANNUAL'))
);

-- 2. Academic Years
CREATE TABLE academic_years (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year integer NOT NULL UNIQUE,
    start_date date,
    end_date date,
    active boolean NOT NULL,
    minimum_attendance numeric(38,2),
    minimum_grade numeric(38,2),
    period_type character varying(255),
    created_at timestamp(6) without time zone,
    CONSTRAINT academic_years_period_type_check CHECK (period_type IN ('BIMESTER', 'TRIMESTER', 'QUADRIMESTER', 'SEMESTER', 'ANNUAL'))
);

-- 3. Academic Periods
CREATE TABLE academic_periods (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id integer NOT NULL,
    name character varying(100) NOT NULL,
    start_date date,
    end_date date,
    closed boolean NOT NULL,
    created_at timestamp(6) without time zone
);

-- 4. Users (Base table for joined-table inheritance)
CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role character varying(20) NOT NULL,
    name character varying(150) NOT NULL,
    email character varying(150) NOT NULL UNIQUE,
    password character varying(255) NOT NULL,
    active boolean NOT NULL,
    last_read_announcements timestamp(6) without time zone,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

-- 5. User Profile Subtypes
CREATE TABLE principals (
    id integer PRIMARY KEY
);

CREATE TABLE secretaries (
    id integer PRIMARY KEY
);

CREATE TABLE teachers (
    id integer PRIMARY KEY
);

CREATE TABLE students (
    id integer PRIMARY KEY,
    enrollment character varying(30) NOT NULL UNIQUE,
    birth_date date,
    guardian_phone character varying(20),
    own_phone character varying(20),
    is_chat_blocked boolean
);

-- 6. Subjects and Teacher Assignments
CREATE TABLE subjects (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(100) NOT NULL UNIQUE,
    description text,
    active boolean NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

CREATE TABLE teacher_subjects (
    teacher_id integer NOT NULL,
    subject_id integer NOT NULL,
    PRIMARY KEY (teacher_id, subject_id)
);

-- 7. Class Rooms
CREATE TABLE class_rooms (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id integer NOT NULL,
    number character varying(20) NOT NULL,
    school_grade character varying(30) NOT NULL,
    shift character varying(20) NOT NULL,
    active boolean NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    CONSTRAINT class_rooms_school_grade_check CHECK (school_grade IN ('PRE_1', 'PRE_2', 'PRE_3', 'FUNDAMENTAL_1', 'FUNDAMENTAL_2', 'FUNDAMENTAL_3', 'FUNDAMENTAL_4', 'FUNDAMENTAL_5', 'FUNDAMENTAL_6', 'FUNDAMENTAL_7', 'FUNDAMENTAL_8', 'FUNDAMENTAL_9', 'MEDIO_1', 'MEDIO_2', 'MEDIO_3')),
    CONSTRAINT class_rooms_shift_check CHECK (shift IN ('MORNING', 'AFTERNOON', 'EVENING', 'FULL_TIME'))
);

-- 8. Teacher Class Subject Association
CREATE TABLE teacher_class_subject (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id integer NOT NULL,
    class_room_id integer NOT NULL,
    subject_id integer NOT NULL,
    min_assessments_per_period integer,
    max_assessments_per_period integer,
    active boolean DEFAULT true NOT NULL,
    created_at timestamp(6) without time zone,
    CONSTRAINT teacher_class_subject_min_assessments_per_period_check CHECK (min_assessments_per_period >= 1),
    CONSTRAINT teacher_class_subject_max_assessments_per_period_check CHECK (max_assessments_per_period >= 1),
    CONSTRAINT ukscth5osdd0vq9imm8i09h3686 UNIQUE (class_room_id, subject_id)
);

-- 9. Enrollments
CREATE TABLE enrollments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL,
    class_room_id integer NOT NULL,
    enrollment_date date,
    general_situation character varying(20),
    active boolean NOT NULL,
    created_at timestamp(6) without time zone,
    CONSTRAINT enrollments_general_situation_check CHECK (general_situation IN ('APPROVED', 'FAILED', 'PENDING')),
    CONSTRAINT uk9em3aonfajpr0m745rw153y7s UNIQUE (student_id, class_room_id)
);

-- 10. Lessons
CREATE TABLE lessons (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_class_subject_id integer NOT NULL,
    lesson_date date NOT NULL,
    lesson_count integer NOT NULL,
    content text,
    notes text,
    active boolean DEFAULT true NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

-- 11. Assessments
CREATE TABLE assessments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_class_subject_id integer NOT NULL,
    period_id integer NOT NULL,
    title character varying(100) NOT NULL,
    description text,
    assessment_date date NOT NULL,
    assessment_type character varying(20) NOT NULL,
    active boolean DEFAULT true NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    CONSTRAINT assessments_assessment_type_check CHECK (assessment_type IN ('EXAM', 'ASSIGNMENT', 'NOTEBOOK'))
);

-- 12. Grades and History
CREATE TABLE grades (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL,
    assessment_id integer NOT NULL,
    score numeric(5,2),
    student_situation character varying(20),
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    CONSTRAINT grades_student_situation_check CHECK (student_situation IN ('APPROVED', 'FAILED', 'PENDING')),
    CONSTRAINT ukiu1e0kh1megq8n6teqxncbgww UNIQUE (student_id, assessment_id)
);

CREATE TABLE grade_history (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_id integer NOT NULL,
    changed_by integer,
    old_grade numeric(5,2),
    new_grade numeric(5,2),
    notes text,
    changed_at timestamp(6) without time zone
);

-- 13. Attendances and History
CREATE TABLE attendances (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id integer NOT NULL,
    student_id integer NOT NULL,
    status character varying(20) NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    CONSTRAINT attendances_status_check CHECK (status IN ('PRESENT', 'ABSENT', 'JUSTIFIED_ABSENCE')),
    CONSTRAINT ukhy36vpj0e4cvdena5jyky8b21 UNIQUE (lesson_id, student_id)
);

CREATE TABLE attendance_history (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id integer NOT NULL,
    changed_by integer,
    old_status character varying(30),
    new_status character varying(30),
    changed_at timestamp(6) without time zone
);

-- 14. Announcements and Classrooms Join
CREATE TABLE announcements (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id integer NOT NULL,
    title character varying(100) NOT NULL,
    message character varying(2000) NOT NULL,
    event_date date,
    target_teachers boolean,
    archived boolean DEFAULT false NOT NULL,
    created_at timestamp(6) without time zone
);

CREATE TABLE announcement_classrooms (
    announcement_id integer NOT NULL,
    class_room_id integer NOT NULL,
    PRIMARY KEY (announcement_id, class_room_id)
);

-- 15. Chat Messages and History
CREATE TABLE chat_messages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id integer NOT NULL,
    classroom_id integer,
    replied_to_id integer,
    content text,
    timestamp timestamp(6) without time zone NOT NULL,
    is_edited boolean DEFAULT false NOT NULL,
    is_deleted boolean DEFAULT false NOT NULL,
    deleted_by_admin boolean DEFAULT false NOT NULL,
    is_global_teacher_chat boolean DEFAULT false NOT NULL,
    archived boolean DEFAULT false NOT NULL
);

CREATE TABLE chat_message_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id character varying(255) NOT NULL,
    message_type character varying(255) NOT NULL,
    content text NOT NULL,
    created_at timestamp(6) without time zone NOT NULL
);

CREATE TABLE chat_read_receipts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    classroom_id integer,
    last_read_message_id integer NOT NULL,
    last_read_at timestamp(6) without time zone NOT NULL,
    is_global_teacher_chat boolean DEFAULT false NOT NULL
);

CREATE TABLE chat_hidden_messages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    message_id integer NOT NULL,
    hidden_at timestamp(6) without time zone NOT NULL
);

-- 16. Security Tokens
CREATE TABLE refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    token character varying(512) NOT NULL UNIQUE,
    expires_at timestamp(6) without time zone NOT NULL,
    revoked boolean NOT NULL,
    created_at timestamp(6) without time zone
);

CREATE TABLE password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    token character varying(255) NOT NULL UNIQUE,
    expires_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone
);


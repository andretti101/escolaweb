CREATE TABLE meal_menu_slots (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id integer NOT NULL,
    day_of_week character varying(20) NOT NULL,
    meal_period character varying(20) NOT NULL,
    title character varying(150) NOT NULL,
    description character varying(500),
    nutritional_notes character varying(255),
    created_at timestamp(6) without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(6) without time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT meal_menu_slots_day_of_week_check CHECK (day_of_week IN ('SEGUNDA', 'TERCA', 'QUARTA', 'QUINTA', 'SEXTA', 'SABADO')),
    CONSTRAINT meal_menu_slots_meal_period_check CHECK (meal_period IN ('MORNING', 'LUNCH', 'AFTERNOON')),
    CONSTRAINT fk_meal_menu_slots_academic_year FOREIGN KEY (academic_year_id) REFERENCES academic_years(id) ON DELETE CASCADE,
    CONSTRAINT uk_meal_menu_slots_year_day_period UNIQUE (academic_year_id, day_of_week, meal_period)
);

CREATE INDEX idx_meal_menu_year_day ON meal_menu_slots(academic_year_id, day_of_week);

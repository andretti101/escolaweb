CREATE TABLE timetable_slots (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id integer NOT NULL,
    teacher_class_subject_id integer NOT NULL,
    day_of_week character varying(20) NOT NULL,
    start_time time without time zone NOT NULL,
    end_time time without time zone NOT NULL,
    slot_order integer NOT NULL,
    created_at timestamp(6) without time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT timetable_slots_day_of_week_check CHECK (day_of_week IN ('SEGUNDA', 'TERCA', 'QUARTA', 'QUINTA', 'SEXTA', 'SABADO')),
    CONSTRAINT timetable_slots_time_check CHECK (start_time < end_time),
    CONSTRAINT timetable_slots_slot_order_check CHECK (slot_order >= 1),
    CONSTRAINT fk_timetable_slots_classroom FOREIGN KEY (classroom_id) REFERENCES class_rooms(id) ON DELETE CASCADE,
    CONSTRAINT fk_timetable_slots_teacher_class_subject FOREIGN KEY (teacher_class_subject_id) REFERENCES teacher_class_subject(id) ON DELETE CASCADE
);

CREATE INDEX idx_timetable_classroom_day ON timetable_slots(classroom_id, day_of_week);
CREATE INDEX idx_timetable_teacher_class_subject ON timetable_slots(teacher_class_subject_id);
CREATE INDEX idx_timetable_day_time ON timetable_slots(day_of_week, start_time, end_time);
